#!/usr/bin/env python3
"""Generate CABundle.cpp, the root CA bundle used to verify TLS servers.

The output uses the ESP-IDF certificate bundle format that
WiFiClientSecure::setCACertBundle() expects. Each entry only holds the
subject name and public key of a root certificate, so a small set of roots
costs a few KB instead of the 64KB full Mozilla bundle that ships with the
core.

    big-endian u16 number of certificates
    for each certificate, sorted by subject:
        u16 subject length, u16 public key length,
        subject (DER Name), public key (DER SubjectPublicKeyInfo)

usage: tools/gen_ca_bundle.py tools/ca-roots.pem > CABundle.cpp
"""
import base64
import re
import sys


def der_element(data, pos):
    """Return (start, end) of the DER element at pos, including its header."""
    length = data[pos + 1]
    hdr = 2
    if length & 0x80:
        n = length & 0x7F
        length = int.from_bytes(data[pos + 2:pos + 2 + n], 'big')
        hdr += n
    return pos, pos + hdr + length


def der_children(data, start, end):
    """Return the elements inside the constructed element data[start:end]."""
    _, inner = der_element(data, start)
    length = data[start + 1]
    pos = start + 2 + (length & 0x7F if length & 0x80 else 0)
    out = []
    while pos < end:
        s, e = der_element(data, pos)
        out.append((s, e))
        pos = e
    return out


def subject_and_key(cert):
    s, e = der_element(cert, 0)
    tbs = der_children(cert, s, e)[0]
    fields = der_children(cert, *tbs)
    if cert[fields[0][0]] == 0xA0:  # explicit version
        fields = fields[1:]
    # serialNumber, signature, issuer, validity, subject, subjectPublicKeyInfo
    subject = cert[fields[4][0]:fields[4][1]]
    key = cert[fields[5][0]:fields[5][1]]
    return subject, key


def main():
    pem = open(sys.argv[1]).read()
    certs = []
    for name, body in re.findall(r'# ([^\n]*)\n-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----', pem, re.S):
        subject, key = subject_and_key(base64.b64decode(body))
        certs.append((subject, key, name.strip()))
    certs.sort(key=lambda c: c[0])
    bundle = len(certs).to_bytes(2, 'big')
    for subject, key, _ in certs:
        bundle += len(subject).to_bytes(2, 'big') + len(key).to_bytes(2, 'big') + subject + key

    print('// Generated by tools/gen_ca_bundle.py from tools/ca-roots.pem. Do not edit.')
    print('// Root CAs:')
    for _, _, name in certs:
        print(f'//   {name}')
    print('#include "CABundle.h"')
    print(f'const uint8_t ca_bundle[{len(bundle)}] = {{')
    for i in range(0, len(bundle), 16):
        print('  ' + ', '.join(f'0x{b:02x}' for b in bundle[i:i + 16]) + ',')
    print('};')


if __name__ == '__main__':
    main()
